Import("env")

import csv
import os


PROJECT_DIR = env.subst("$PROJECT_DIR")
BUILD_DIR = env.subst("$BUILD_DIR")

PARTITIONS_FILE = os.path.join(
    PROJECT_DIR,
    "partitions.csv"
)

PARTITION_NAME = "web"


def parse_value(value):
    value = value.strip()

    if value.lower().startswith("0x"):
        return int(value, 16)

    value = value.lower()

    if value.endswith("k"):
        return int(value[:-1]) * 1024

    if value.endswith("m"):
        return int(value[:-1]) * 1024 * 1024

    return int(value)


def find_partition(name):
    with open(PARTITIONS_FILE, "r", encoding="utf-8") as f:
        reader = csv.reader(f)

        for row in reader:
            if not row:
                continue

            if row[0].strip().startswith("#"):
                continue

            if row[0].strip() != name:
                continue

            if len(row) < 5:
                raise RuntimeError(
                    f"Invalid partition definition: {row}"
                )

            offset = row[3].strip()
            size = row[4].strip()

            if not offset:
                raise RuntimeError(
                    f"Partition '{name}' requires an explicit offset"
                )

            return {
                "offset": parse_value(offset),
                "size": parse_value(size),
            }

    raise RuntimeError(
        f"Partition '{name}' not found in {PARTITIONS_FILE}"
    )


def upload_web(source, target, env):
    partition = find_partition(PARTITION_NAME)

    # Image generated by PlatformIO buildfs
    image = os.path.join(
        BUILD_DIR,
        "littlefs.bin"
    )

    if not os.path.isfile(image):
        raise RuntimeError(
            f"LittleFS image not found: {image}"
        )

    offset = "0x{:X}".format(partition["offset"])

    print()
    print("========================================")
    print(" pmgHub WEB upload")
    print("========================================")
    print(f"Partition : {PARTITION_NAME}")
    print(f"Offset    : {offset}")
    print(f"Size      : {partition['size']} bytes")
    print(f"Image     : {image}")
    print("========================================")
    print()

    # Reuse PlatformIO's native uploader configuration
    env.Replace(
        UPLOADERFLAGS=[
            "--chip",
            "esp32s3",
            "--port",
            "$UPLOAD_PORT",
            "--baud",
            "$UPLOAD_SPEED",
            "--before",
            "default_reset",
            "--after",
            "hard_reset",
            "write_flash",
            offset,
        ]
    )

    env.Execute(
        '"$UPLOADER" $UPLOADERFLAGS "{}"'.format(image)
    )


env.AddCustomTarget(
    name="uploadweb",
    dependencies=["buildfs"],
    actions=upload_web,
    title="Upload Web",
    description="Build and upload pmgHub WEB LittleFS partition",
)